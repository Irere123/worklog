export type Product = keyof typeof MARKS;

export function isProduct(name: string): name is Product {
  return Object.hasOwn(MARKS, name);
}

/**
 * A tool's own logo in its own colours. Sized like a Phosphor icon of the same `size`, whose
 * glyphs leave a margin inside their box, so the two sit side by side without one looking loud.
 */
export function ProductMark({
  product: name,
  size = 16,
}: {
  product: Product;
  size?: number;
}) {
  const { width, parts } = MARKS[name];
  const inset = width * 0.08;
  return (
    <svg
      width={size}
      height={size}
      viewBox={`${-inset} ${-inset} ${width + inset * 2} ${24 + inset * 2}`}
      aria-hidden
      {...stylex.props(styles.mark)}
    >
      {parts.map((part) => (
        <path key={part.d} d={part.d} {...stylex.props(fills[part.fill])} />
      ))}
    </svg>
  );
}

